/**
 * The outermost HTML shell for the application.
 * Manages the document `<head>` and injected scripts.
 *
 * @param {Object} props - Component props.
 * @param {ReactNode} props.children - The child components to render within `<body>`.
 * @returns {ReactNode} The HTML document structure.
 */
function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

/**
 * The root component of the application.
 * Provides global contexts (like QueryClient) and renders the matched route.
 *
 * @returns {ReactNode} The root application structure.
 */
function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
